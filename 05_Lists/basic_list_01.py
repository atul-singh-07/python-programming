# Performing basic operations on list, like accessing, Updation And printing of list element using index values.

marks=[10,20,30,40,50]
student=["Atul","Nancy","Tanish"]
# print Type
print(type(marks))
print(type(student))

# accessing the values of list by using ---> index values
print(marks[0])
print(marks[1])

# accessing the values of student List.
print(student[0])
print(student[1])

# updation in both marks and student lists.
marks[0]=90
marks[1]=95
print(marks[0])
print(marks[1])

student[2]="Tanisha"
print(student[2])